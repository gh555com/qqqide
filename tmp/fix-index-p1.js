var fs = require('fs');
var p = 'e:/s/wol/py/qqq-shell-v2/server-app/ai-panel/index.html';
var lines = fs.readFileSync(p, 'utf8').split('\n');

// ============================================================
// 1. Add _formatSizeCompact after formatBytes (line 717 in file, 716 0-indexed)
// ============================================================
for (var i = 0; i < lines.length; i++) {
    if (lines[i].indexOf('function formatBytes(n)') >= 0) {
        // Find the closing } of formatBytes
        for (var j = i; j < i + 15; j++) {
            if (lines[j].trim() === '}' && lines[j].indexOf('function') < 0) {
                lines.splice(j + 1, 0,
                    '',
                    'function _formatSizeCompact(bytes) {',
                    '  if (!bytes || bytes < 0) return \'0\';',
                    '  if (bytes < 1024) return bytes + \' B\';',
                    '  var kb = bytes / 1024;',
                    '  if (kb < 1024) return kb.toFixed(1) + \'k\';',
                    '  var mb = kb / 1024;',
                    '  return mb.toFixed(2) + \'M\';',
                    '}'
                );
                break;
            }
        }
        break;
    }
}

// ============================================================
// 2. Add chat.txt streaming state + functions before sendMessage
//    Find: "async function sendMessage()"
// ============================================================
var smIdx = -1;
for (var i = 0; i < lines.length; i++) {
    if (lines[i].indexOf('async function sendMessage()') >= 0) { smIdx = i; break; }
}

var chatTxtCode = [
    '// ═══ Chat.txt streaming (per-floor) ═══',
    'var _chatTxtPath = null;',
    'var _chatTxtPollTimer = null;',
    'var _chatTxtLiveTimer = null;',
    'var _chatTxtOpenInEditor = false;',
    'var _chatTxtA1Block = null;',
    '',
    '// Count total rooms across all houses',
    'function _countRooms(houses) {',
    '  if (!houses) return 0;',
    '  var n = 0;',
    '  for (var i = 0; i < houses.length; i++) {',
    '    if (houses[i].tools) n += houses[i].tools.length;',
    '  }',
    '  return n;',
    '}',
    '',
    '// Build full chat.txt content from current agent state',
    'function _buildChatTxtLines(agent, floorNum, userInput, visionInput, timing) {',
    '  var houses = agent._houses || [];',
    '  var lines = [];',
    '  var pad = function(n) { return String(n).padStart(2, \'0\'); };',
    '  var ts = function(d) {',
    '    if (!d) d = new Date();',
    '    return d.getFullYear() + \'-\' + pad(d.getMonth()+1) + \'-\' + pad(d.getDate()) + \' \' + pad(d.getHours()) + \':\' + pad(d.getMinutes()) + \':\' + pad(d.getSeconds());',
    '  };',
    '',
    '  // Floor header',
    '  var now = new Date();',
    '  var floorTs = timing && timing.floorStartServerMs ? new Date(timing.floorStartServerMs) : now;',
    '  lines.push(\'floor.\' + floorNum + \'   \' + ts(floorTs));',
    '  lines.push(\'\');',
    '',
    '  // User input',
    '  if (userInput) { lines.push(userInput); lines.push(\'\'); }',
    '  if (visionInput) { lines.push(visionInput); lines.push(\'\'); }',
    '',
    '  // Houses',
    '  for (var hi = 0; hi < houses.length; hi++) {',
    '    var h = houses[hi];',
    '    var houseTs = h.ts ? new Date(h.ts) : now;',
    '    lines.push(\'════ HOUSE \' + h.index + \' ════ \' + ts(houseTs) + \' [\' + h.ms + \'ms] ════\');',
    '',
    '    if (h.reasoning) {',
    '      lines.push(\'<thinking>\');',
    '      lines.push(h.reasoning);',
    '      lines.push(\'</thinking>\');',
    '      lines.push(\'\');',
    '    }',
    '',
    '    if (h.tools && h.tools.length > 0) {',
    '      for (var ti = 0; ti < h.tools.length; ti++) {',
    '        var t = h.tools[ti];',
    '        var argsStr = (typeof t.args === \'string\') ? t.args : JSON.stringify(t.args || {});',
    '        lines.push(\'  ── ROOM \' + h.index + \'.\' + (ti + 1) + \'  \' + t.name + \'(\' + argsStr + \') ──\');',
    '        if (h.toolResults && h.toolResults[ti]) {',
    '          lines.push(h.toolResults[ti]);',
    '          lines.push(\'\');',
    '        }',
    '      }',
    '    }',
    '',
    '    if (h.type === \'final\' && h.answer) {',
    '      lines.push(\'  <answer>\');',
    '      lines.push(h.answer);',
    '      lines.push(\'  </answer>\');',
    '    }',
    '',
    '    lines.push(\'\');',
    '  }',
    '',
    '  // Floor stats',
    '  if (timing) {',
    '    lines.push(\'════ floor \' + floorNum + \' stats ════\');',
    '    lines.push(\'network: \' + (timing.networkMs ? timing.networkMs.toFixed(0) : \'0\') + \'ms  deepseek: \' + (timing.deepseekMs ? timing.deepseekMs.toFixed(0) : \'0\') + \'ms  tool: \' + (timing.toolMs ? timing.toolMs.toFixed(0) : \'0\') + \'ms\');',
    '  }',
    '  return lines;',
    '}',
    '',
    '// Safe write with external-edit conflict guard',
    'async function _safeWriteChatTxt(path, lines, lastMtime) {',
    '  var bridge = window.parent && window.parent.qqqBridge;',
    '  if (!bridge) return false;',
    '  try {',
    '    var stat = await bridge.fs.stat(path).catch(function() { return null; });',
    '    if (lastMtime > 0 && stat && stat.mtimeMs && Math.abs(stat.mtimeMs - lastMtime) > 100) {',
    '      console.warn(\'[chat-txt] externally modified, skipping write\');',
    '      return false;',
    '    }',
    '    await bridge.fs.write(path, lines.join(\'\\n\'));',
    '    return true;',
    '  } catch (e) {',
    '    console.warn(\'[chat-txt] write failed:\', e && e.message);',
    '    return false;',
    '  }',
    '}',
    '',
    '// Initialize A1 tofu block (above clock, below content)',
    'function _initA1Block(aiDiv, chatTxtPath) {',
    '  if (aiDiv._a1Block) return aiDiv._a1Block;',
    '  var block = document.createElement(\'div\');',
    '  block.className = \'msg-a1\';',
    '  block.innerHTML = \'<div class=\"msg-a1-r1\">HOUSE 0   ROOM 0</div><div class=\"msg-a1-r2\">0</div>\';',
    '  var clockBlock = aiDiv._clockBlock;',
    '  if (clockBlock) {',
    '    aiDiv.insertBefore(block, clockBlock);',
    '  } else {',
    '    aiDiv.appendChild(block);',
    '  }',
    '  block._r1 = block.querySelector(\'.msg-a1-r1\');',
    '  block._r2 = block.querySelector(\'.msg-a1-r2\');',
    '  block._path = chatTxtPath;',
    '  block._aiDiv = aiDiv;',
    '  block.onclick = function() {',
    '    parent.postMessage({ type: \'qqq-file-open-right\', path: chatTxtPath, readOnly: true }, \'*\');',
    '    _chatTxtOpenInEditor = true;',
    '    // Start Monaco live refresh if not already running',
    '    if (!_chatTxtLiveTimer) {',
    '      _chatTxtLiveTimer = setInterval(async function() {',
    '        var b = window.parent && window.parent.qqqBridge;',
    '        if (!b) return;',
    '        try {',
    '          var content = await b.fs.read(chatTxtPath);',
    '          parent.postMessage({ type: \'qqq-editor-refresh\', path: chatTxtPath, content: content }, \'*\');',
    '        } catch (_) {}',
    '      }, 5000);',
    '    }',
    '  };',
    '  aiDiv._a1Block = block;',
    '  _chatTxtA1Block = block;',
    '  return block;',
    '}',
    '',
    '// Start A1 polling + streaming chat.txt writes',
    'function _startChatTxtStream(aiDiv, chatTxtPath, agent, floorNum, userContent, visionContent) {',
    '  _stopChatTxtStream();',
    '  var lastWriteMs = 0;',
    '  var lastMtime = 0;',
    '  var lastHouseCount = 0;',
    '  var lastRoomCount = 0;',
    '',
    '  _chatTxtPollTimer = setInterval(function() {',
    '    if (!agent._houses) return;',
    '    var hCount = agent._houses.length;',
    '    var rCount = _countRooms(agent._houses);',
    '',
    '    // Update A1 display every tick',
    '    var a1 = aiDiv._a1Block || _chatTxtA1Block;',
    '    if (a1 && a1._r1) {',
    '      a1._r1.textContent = \'HOUSE \' + hCount + \'   ROOM \' + rCount;',
    '    }',
    '',
    '    // Write chat.txt every 5s or when new houses appear',
    '    var now = Date.now();',
    '    var hasNew = hCount > lastHouseCount || rCount > lastRoomCount;',
    '    if (now - lastWriteMs > 5000 || hasNew) {',
    '      lastWriteMs = now;',
    '      lastHouseCount = hCount;',
    '      lastRoomCount = rCount;',
    '      var timing = agent._floorTiming;',
    '      // Extract user text from agent context',
    '      var uiText = \'\';',
    '      if (agent._lastUserInput && agent._lastUserInput.text) {',
    '        uiText = agent._lastUserInput.text.replace(/\\n/g, \' \').trim();',
    '      }',
    '      var vtText = (agent._lastUserInput && agent._lastUserInput.vision) ? agent._lastUserInput.vision.trim() : \'\';',
    '      var lines = _buildChatTxtLines(agent, floorNum, uiText, vtText, timing);',
    '      _safeWriteChatTxt(chatTxtPath, lines, lastMtime).then(function(ok) {',
    '        if (ok) {',
    '          // Update file size on A1',
    '          var b2 = window.parent && window.parent.qqqBridge;',
    '          if (b2 && a1 && a1._r2) {',
    '            b2.fs.stat(chatTxtPath).then(function(st) {',
    '              if (st && st.size) {',
    '                a1._r2.textContent = _formatSizeCompact(st.size);',
    '                lastMtime = st.mtimeMs || 0;',
    '              }',
    '            }).catch(function(){});',
    '          }',
    '          // Monaco live refresh',
    '          if (_chatTxtOpenInEditor) {',
    '            parent.postMessage({ type: \'qqq-editor-refresh\', path: chatTxtPath, content: lines.join(\'\\n\') }, \'*\');',
    '          }',
    '        }',
    '      }).catch(function(){});',
    '    }',
    '  }, 1000);',
    '}',
    '',
    '// Finalize chat.txt after floor completes',
    'async function _finalizeChatTxt(aiDiv, chatTxtPath, agent, floorNum, timing) {',
    '  _stopChatTxtStream();',
    '  if (!chatTxtPath) return;',
    '  var uiText = \'\';',
    '  var vtText = \'\';',
    '  if (agent._lastUserInput) {',
    '    uiText = agent._lastUserInput.text ? agent._lastUserInput.text.replace(/\\n/g, \' \').trim() : \'\';',
    '    vtText = agent._lastUserInput.vision ? agent._lastUserInput.vision.trim() : \'\';',
    '  }',
    '  var lines = _buildChatTxtLines(agent, floorNum, uiText, vtText, timing || agent._floorTiming);',
    '  var bridge = window.parent && window.parent.qqqBridge;',
    '  if (!bridge) return;',
    '  try {',
    '    await bridge.fs.write(chatTxtPath, lines.join(\'\\n\'));',
    '    var st = await bridge.fs.stat(chatTxtPath).catch(function(){ return null; });',
    '    var a1 = aiDiv._a1Block;',
    '    if (a1 && a1._r2 && st && st.size) {',
    '      a1._r2.textContent = _formatSizeCompact(st.size);',
    '    }',
    '    // Final Monaco refresh',
    '    if (_chatTxtOpenInEditor) {',
    '      parent.postMessage({ type: \'qqq-editor-refresh\', path: chatTxtPath, content: lines.join(\'\\n\') }, \'*\');',
    '    }',
    '    console.log(\'[chat-txt] finalized: \' + chatTxtPath + \' (\' + lines.length + \' lines)\');',
    '  } catch (e) {',
    '    console.warn(\'[chat-txt] finalize failed:\', e && e.message);',
    '  }',
    '}',
    '',
    'function _stopChatTxtStream() {',
    '  if (_chatTxtPollTimer) { clearInterval(_chatTxtPollTimer); _chatTxtPollTimer = null; }',
    '  _chatTxtA1Block = null;',
    '  _chatTxtPath = null;',
    '}',
    '',
    'function _stopChatTxtLive() {',
    '  if (_chatTxtLiveTimer) { clearInterval(_chatTxtLiveTimer); _chatTxtLiveTimer = null; }',
    '  _chatTxtOpenInEditor = false;',
    '}',
    ''
];

lines.splice(smIdx, 0, ...chatTxtCode);

fs.writeFileSync(p, lines.join('\n'), 'utf8');
console.log('Phase 1 OK');
